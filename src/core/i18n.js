export function t(key, params = {}) {
    const lang = AppState.language || 'en';
    let text = translations[lang]?.[key] || translations['en'][key] || key;

    Object.keys(params).forEach(p => {
        text = text.replace(`{${p}}`, params[p]);
    });

    return text;
}

export function detectLanguage() {
    const saved = localStorage.getItem('focus_app_lang');
    if (saved && ['tr', 'en', 'de'].includes(saved)) return saved;

    // Default to English as per user request
    return 'en';
}

export function detectTranslationTarget() {
    const saved = localStorage.getItem('focus_app_target_lang');
    if (saved) return saved;
    return 'de'; // Default to German as per user request
}

export function updateStaticTranslations() {
    if (document.documentElement) {
        document.documentElement.lang = AppState.language || 'tr';
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        // setAttribute, not `.placeholder`: the note areas are contenteditable
        // <div>s whose placeholder is drawn by CSS from attr(placeholder), and a
        // <div> has no placeholder property - assigning one silently created an
        // expando and left the hardcoded markup text on screen in every language.
        el.setAttribute('placeholder', t(key));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        el.setAttribute('aria-label', t(key));
    });
}
