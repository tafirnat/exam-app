export function t(key, params = {}) {
    const lang = AppState.language || 'en';
    let text = translations[lang]?.[key] || translations['en'][key] || key;

    Object.keys(params).forEach(p => {
        text = text.replace(`{${p}}`, params[p]);
    });

    return text;
}

export function detectLanguage() {
    const saved = readString('focus_app_lang');
    if (saved && ['tr', 'en', 'de'].includes(saved)) return saved;

    // Fallback to system language if supported
    if (typeof navigator !== 'undefined' && navigator.language) {
        const sysLang = navigator.language.split('-')[0].toLowerCase();
        if (['tr', 'en', 'de'].includes(sysLang)) {
            return sysLang;
        }
    }

    // Default to English as per user request
    return 'en';
}

export function detectTranslationTarget() {
    const saved = readString('focus_app_target_lang');
    if (saved) return saved;
    return 'de'; // Default to German as per user request
}

export function updateStaticTranslations() {
    if (document.documentElement) {
        document.documentElement.lang = AppState.language || 'en';
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        // setAttribute, not `.placeholder`: the note areas are contenteditable
        // <div>s whose placeholder is drawn by CSS from attr(placeholder), and a
        // <div> has no placeholder property - assigning one silently created an
        // expando and left the hardcoded markup text on screen in every language.
        el.setAttribute('placeholder', t(key));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        el.setAttribute('aria-label', t(key));
    });

    updateDocumentTitle();
}

export function updateDocumentTitle(viewName = null) {
    const testView = document.getElementById('testView');
    const isTestActive = viewName === 'test' || (testView && testView.style.display === 'flex');
    
    if (isTestActive && AppState.testTracking) {
        let title = AppState.testTracking.sourceTitle;
        
        if (AppState.currentTest && AppState.currentTest.length > 0 && typeof AppState.currentIndex === 'number') {
            const currentQId = AppState.currentTest[AppState.currentIndex];
            const currentQ = AppState.questionMap?.[currentQId];
            if (currentQ && currentQ.sourceId && AppState.sources) {
                const specificSource = AppState.sources.find(s => s.id === currentQ.sourceId);
                if (specificSource && specificSource.name) {
                    title = specificSource.name;
                }
            }
        }
        
        if (title) {
            document.title = title;
            return;
        }
    }
    
    document.title = t('app_title_short') || "ExamApp";
}
